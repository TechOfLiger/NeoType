/* ---------- SAVE RESULT ---------- */

function saveResult(
    wpm,
    accuracy,
    chars,
    score
) {

    const result = {

        wpm,

        accuracy,

        chars,

        score,

        date:
            new Date().toLocaleString()

    };


    history.unshift(result);


    history =
        history.slice(0, 10);


    localStorage.setItem(
        "typexHistory",
        JSON.stringify(history)
    );


    loadStats();

}


/* ---------- LOAD STATS ---------- */

function loadStats() {

    if (!history.length) {

        bestWpm.textContent = "0";

        bestAccuracy.textContent =
            "0%";

        testsCompleted.textContent =
            "0";

        historyList.innerHTML = `
            <div class="empty-history">
                No tests completed yet.
            </div>
        `;

        return;

    }


    const maxWpm =
        Math.max(
            ...history.map(
                item => item.wpm
            )
        );


    const maxAccuracy =
        Math.max(
            ...history.map(
                item => item.accuracy
            )
        );


    bestWpm.textContent =
        maxWpm;


    bestAccuracy.textContent =
        `${maxAccuracy}%`;


    testsCompleted.textContent =
        history.length;


    renderHistory();

}


