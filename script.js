/* ---------- GENERATE TEXT ---------- */

function generateText() {

    let difficultyText =
        texts[difficulty.value];

    currentText =
        difficultyText[
            Math.floor(
                Math.random() *
                difficultyText.length
            )
        ];

    applyTypingMode();

    renderText();

}


/* ---------- APPLY MODE ---------- */

function applyTypingMode() {

    if (typingMode.value === "numbers") {

        currentText +=
            " 2026 123 456 789 42 100 500 1000";

    }

    if (typingMode.value === "punctuation") {

        currentText +=
            " How fast can you type? Try your best! Keep going, and don't stop.";

    }

}


/* ---------- RENDER TEXT ---------- */

function renderText() {

    textDisplay.innerHTML = "";

    [...currentText].forEach(
        (char, index) => {

            const span =
                document.createElement("span");

            span.className = "char";

            span.textContent = char;

            if (index === 0) {

                span.classList.add("current");

            }

            textDisplay.appendChild(span);

        }
    );

    totalChars.textContent =
        currentText.length;

}


/* ---------- INPUT EVENT ---------- */

typingInput.addEventListener(
    "input",
    handleTyping
);


function handleTyping() {

    if (finished) return;


    if (!started) {

        startTest();

    }


    const typed =
        typingInput.value;


    errors = 0;


    const characters =
        document.querySelectorAll(".char");


    characters.forEach(
        (char, index) => {

            char.classList.remove(
                "correct",
                "incorrect",
                "current"
            );


            if (index < typed.length) {

                if (
                    typed[index] ===
                    currentText[index]
                ) {

                    char.classList.add(
                        "correct"
                    );

                } else {

                    char.classList.add(
                        "incorrect"
                    );

                    errors++;

                }

            }

        }
    );


    if (typed.length < currentText.length) {

        characters[
            typed.length
        ]?.classList.add("current");

    }


    charCount.textContent =
        typed.length;


    errorsDisplay.textContent =
        errors;


    calculateStats();

    updateProgress();


    if (
        typed.length >=
        currentText.length
    ) {

        finishTest();

    }

}


/* ---------- START ---------- */

function startTest() {

    started = true;

    startTime = Date.now();

    timer = setInterval(
        countdown,
        1000
    );

    typingInput.focus();

}


/* ---------- COUNTDOWN ---------- */

function countdown() {

    timeLeft--;

    updateTimer();

    if (timeLeft <= 0) {

        finishTest();

    }

}


/* ---------- UPDATE TIMER ---------- */

function updateTimer() {

    timerDisplay.textContent =
        timeLeft;

}


/* ---------- CALCULATE ---------- */

function calculateStats() {

    const typed =
        typingInput.value;


    if (!typed.length) {

        wpmDisplay.textContent = "0";

        accuracyDisplay.textContent =
            "100%";

        return;

    }


    const elapsed =
        Math.max(
            (Date.now() - startTime) / 1000,
            1
        );


    const minutes =
        elapsed / 60;


    const correctChars =
        typed.split("").filter(
            (char, index) =>
                char ===
                currentText[index]
        ).length;


    const wpm =
        Math.round(
            (correctChars / 5) /
            minutes
        );


    const accuracy =
        Math.round(
            (correctChars /
                typed.length) *
            100
        );


    wpmDisplay.textContent =
        Math.max(wpm, 0);


    accuracyDisplay.textContent =
        `${accuracy}%`;

}


/* ---------- PROGRESS ---------- */

function updateProgress() {

    const typed =
        typingInput.value.length;


    const progress =
        Math.min(
            (typed /
                currentText.length) *
            100,
            100
        );


    progressBar.style.width =
        `${progress}%`;


    progressText.textContent =
        `${Math.round(progress)}%`;

}


/* ---------- FINISH ---------- */

function finishTest() {

    if (finished) return;


    finished = true;


    clearInterval(timer);


    typingInput.blur();


    calculateStats();


    const wpm =
        Number(
            wpmDisplay.textContent
        );


    const accuracy =
        Number(
            accuracyDisplay.textContent
                .replace("%", "")
        );


    const chars =
        typingInput.value.length;


    const score =
        Math.round(
            wpm *
            (accuracy / 100)
        );


    saveResult(
        wpm,
        accuracy,
        chars,
        score
    );


    showResult(
        wpm,
        accuracy,
        chars,
        score
    );

}


